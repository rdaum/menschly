"""Pack the game's sound after the sprite images into the blob for the ROM
image's upper bank, and describe it.

    python3 sound_bank.py [assets dir]

The blob (target/bubble-bobble/game-bank.bin, which inject_bank.py puts in
the ROM image) is demo-images.bin (demo_assets.py), then from SOUND_BANK the
music stream (sound_stream.py: the arcade's theme, played at MUSIC_HZ and,
when hurried, HURRY_HZ) and the effects' SID streams (sound_effects.py), each
at an offset from SOUND_BANK.
bubble-sound-bank.mensch says where each lies. run-game.sh makes both.
"""

import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))

import inject_bank  # noqa: E402
import sound_stream  # noqa: E402

# The theme ($30 in the game, $0F when hurried: the same writes).
MUSIC = 0x30
HURRY = 0x0F
# The effects the game plays, and the arcade's commands for them.
EFFECTS = [("BLOW", 0x31), ("POP", 0x25), ("FRUIT", 0x11), ("CAUGHT", 0x0D)]


def main():
    assets = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "target" / "bubble-bobble"
    sound = assets / "sound"
    music, header, _ = sound_stream.stream(MUSIC)
    hurry = json.loads((sound / f"{HURRY:02x}.jsonl").read_text().splitlines()[0])
    blob = bytearray((assets / "demo-images.bin").read_bytes())
    blob += bytes(-len(blob) % 0x100)
    bank = inject_bank.BANK + len(blob)
    blob += music
    effects = []
    for name, cmd in EFFECTS:
        stream = (sound / f"{cmd:02x}.sid").read_bytes()
        effects.append((name, len(blob) - (bank - inject_bank.BANK)))
        blob += stream
    assert len(blob) <= inject_bank.SPACE, f"the game's bank is {len(blob)} bytes, over {inject_bank.SPACE}"
    (assets / "game-bank.bin").write_bytes(blob)
    lines = [
        "module BubbleSoundBank",
        "",
        "# Generated by sound_bank.py; see there.",
        "",
        f"export const SOUND_BANK: u32 = ${bank:x}",
        f"export const MUSIC_HZ = {round(header['timer_a_hz'] * 100)}",
        f"export const HURRY_HZ = {round(hurry['timer_a_hz'] * 100)}",
        f"export const EFFECTS = {len(effects)}",
    ]
    for i, (name, _) in enumerate(effects):
        lines.append(f"export const EFFECT_{name} = {i}")
    lines.append(f"export const EFFECT_AT: [{len(effects)}]u16 = [{', '.join(str(at) for _, at in effects)}]")
    (assets / "bubble-sound-bank.mensch").write_text("\n".join(lines) + "\n")
    sound_bytes = len(blob) - (bank - inject_bank.BANK)
    print(f"game bank: {len(blob)} bytes ({len(music)} music, {sound_bytes - len(music)} effects)")


if __name__ == "__main__":
    main()
